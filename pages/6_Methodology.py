# ── Regulatory context ────────────────────────────────────────────────────────
st.subheader("Regulatory Context")

st.markdown("""
A production version of this product would need to address the following
regulatory frameworks, among others:

- **GDPR (EU 2016/679):** Data minimisation, consent, and the right to a
  meaningful explanation for automated credit-related decisions (Article 22).
- **PSD2 (EU 2015/2366):** Licenced Third-Party Provider status required for
  access to payment account data.
- **EU AI Act:** Credit-scoring systems may be classified as high-risk AI
  under Article 6, requiring conformity assessments and human oversight.
- **CRD IV / CRR:** Capital requirements applying to licenced lenders.

ForkFund in its current form does not satisfy any of these requirements.
It is a demonstration prototype, not a production financial service.
""")
