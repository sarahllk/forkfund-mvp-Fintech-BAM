# ── Synthetic data ────────────────────────────────────────────────────────────
st.subheader("Synthetic Data")

st.markdown("""
All data used in this prototype is generated by a deterministic random process
with a fixed seed. The generator produces 120 restaurant profiles with associated
12-month transaction and POS records, three years of accounting data, and
ten fictional lender profiles.

The generation process is parameterised to produce a realistic spread of
financial health across the dataset — including operators with healthy margins,
seasonally dependent businesses, highly leveraged profiles, and cases of
operational distress. Statistical distributions were calibrated to produce
the score diversity described below, not to match any published industry benchmark.
""")

