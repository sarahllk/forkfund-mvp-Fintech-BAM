# ── Limitations ───────────────────────────────────────────────────────────────
st.subheader("Known Limitations")

st.markdown("""
**Model validity.** Score weights are illustrative starting values.
They were not derived from historical default or repayment data and have not
been backtested against real credit outcomes.

**Single accounting year.** The scoring engine uses only the most recent
accounting year for debt burden, repayment capacity, and cost structure.
A production model would use year-on-year trend analysis.

**No revenue seasonality detection.** The coefficient-of-variation approach
treats all monthly revenue variance as instability, without distinguishing
between predictable seasonal patterns and structural volatility.

**Data completeness is binary per source.** A source with one record is treated
identically to one with 700. A production implementation would weight sources
by record density and recency.

**Session persistence.** There is no database. All state is held in the browser
session and is lost on page refresh. This is an intentional MVP constraint.

**Lender dataset.** The ten fictional lenders cover a limited range of criteria.
Some restaurant profiles will return zero eligible lenders — particularly
distressed profiles — which is an accurate reflection of their eligibility,
not a tool defect.
""")

