with col_table:
    st.markdown("""
| Dimension | Weight | Data source | Method |
|---|---|---|---|
| Revenue stability | 20% | POS | 1 – coefficient of variation across monthly net revenue |
| Cash-flow strength | 20% | PSD2 | Net inflow margin normalised to a 30% benchmark |
| Debt burden | 15% | Accounting | 1 – (debt / revenue), capped at zero |
| Repayment capacity | 15% | Accounting | EBITDA margin normalised to a 30% benchmark |
| Cost structure | 10% | Accounting | Linear scale from 45% cost ratio (100) to 85% (0) |
| Business maturity | 10% | KvK | Years since registration, capped at 10 years |
| Data completeness | 10% | All | Fraction of the four sources that are populated |
""")

